# mkfont.py - CyborgOS's characters 160-255 for LANG: KOI8.FNR (Russian, KOI8-R) and LATIN1.FNR
# (Spanish / English, Latin-1). Each is a recipe, 96 records, built on the machine's own font
# (characters 32-127, each bank's copy at #F300) when LANG runs - so no ROM font is carried here:
#   0                 blank
#   1 c               character c as it is
#   2 c a             character c with accent a over it (a capital moved down a row first)
#   3 c               character c turned upside down (and round: ! -> inverted !, ? -> inverted ?)
#   4 b0 .. b7        an original 8 x 8 glyph (CyborgOS's own drawing, in the CPC font's style)
# Accents: 1 acute, 2 grave, 3 circumflex, 4 diaeresis, 5 tilde, 6 cedilla (under), 7 ring.
#   python3 mkfont.py [rom]   writes the two .FNR files; with a 6128 ROM: a preview (development)
