def G(*rows):                       # an original glyph from 8 strings of . and #
    assert len(rows) == 8, rows
    out = []
    for r in rows:
        assert len(r) == 8, r
        out.append(sum(0x80 >> i for i, ch in enumerate(r) if ch == '#'))
    return (4, out)

