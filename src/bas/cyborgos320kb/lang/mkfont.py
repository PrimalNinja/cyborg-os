COPY = {'А':'A','В':'B','Е':'E','К':'K','М':'M','Н':'H','О':'O','Р':'P','С':'C','Т':'T','Х':'X',
        'а':'a','е':'e','о':'o','р':'p','с':'c','у':'y','х':'x'}
ACC = {'´':1, '`':2, '^':3, '¨':4, '~':5, '¸':6, '°':7}

def recipe(ch):
    if ch in O: return O[ch]
    if ch in COPY: return (1, [ord(COPY[ch])])
    if ch == 'ё': return (2, [ord('e'), 4])
    if ch == 'Ё': return (2, [ord('E'), 4])
    if ch == '¡': return (3, [ord('!')])
    if ch == '¿': return (3, [ord('?')])
    if ch == '«': return G("........", "........", "..##..##", ".##..##.", "##..##..", ".##..##.", "..##..##", "........")
    if ch == '»': return G("........", "........", "##..##..", ".##..##.", "..##..##", ".##..##.", "##..##..", "........")
    if ch == '°': return G("..###...", ".##.##..", "..###...", "........", "........", "........", "........", "........")
    if ch == '£': return G("..###...", ".##.##..", ".##.....", "#####...", ".##.....", ".##..##.", "######..", "........")
    if ch == 'ª': return G(".####...", "....##..", ".#####..", "##..##..", ".###.##.", "........", "#######.", "........")
    if ch == 'º': return G("..###...", ".##.##..", ".##.##..", "..###...", "........", "........", "#######.", "........")
    import unicodedata
    d = unicodedata.normalize('NFD', ch)
    if len(d) == 2 and d[0].isascii() and d[0].isalpha():
        mark = {'\u0301':1, '\u0300':2, '\u0302':3, '\u0308':4, '\u0303':5, '\u0327':6, '\u030a':7}.get(d[1])
        if mark: return (2, [ord(d[0]), mark])
    return (0, [])

def build(enc):
    recs = []
    for b in range(160, 256):
        try: ch = bytes([b]).decode(enc)
        except UnicodeDecodeError: ch = ''
        recs.append(recipe(ch) if ch else (0, []))
    data = bytearray()
    for op, args in recs:
        data.append(op); data += bytes(args)
    return recs, bytes(data)

# ---- the composer: the same steps LANG.bas takes on the machine
ACCROW = {1: [0x0C, 0x18], 2: [0x30, 0x18], 3: [0x18, 0x66], 4: [0x66, 0x00], 5: [0x76, 0xDC], 6: None, 7: [0x18, 0x18]}
def compose(font, recs):
    out = []
    for op, a in recs:
        if op == 0: g = [0] * 8
        elif op == 1: g = list(font(a[0]))
        elif op == 3: g = [int('{:08b}'.format(x)[::-1], 2) for x in reversed(font(a[0]))]   # 180 degrees
        elif op == 4: g = list(a)
        else:
            base = list(font(a[0])); m = a[1]
            if m == 6:                                       # cedilla: under, in row 7
                g = base[:]; g[7] = 0x0C if chr(a[0]).islower() else 0x18
            elif chr(a[0]).isupper():                        # a capital: down a row, the accent's top row
                g = [ACCROW[m][0] if m != 4 else 0x66] + base[0:7]
                if m == 4: g[0] = 0x66
            else:                                            # small: the accent in rows 0-1
                g = base[:]
                if chr(a[0]) == 'i': g[0] = 0; g[1] = 0      # (dotless first)
                if chr(a[0]) in 'bdfhklt': g = base[:]       # (tall letters: rows 0-1 left as they are)
                g[0] |= ACCROW[m][0]; g[1] |= ACCROW[m][1]
        out.append(g)
    return out

